  function_owner=self,
  font_size=380,
  width=350,
  height=436,
 }
 butWrapper(params,{-1.7,0.1,1.8},"<","Previous Set","prevSet")
 butWrapper(params,{1.7,0.1,1.8},">","Next Set","nextSet")
 local XMLTable={}
 params.color={1,1,1,0}

 for Type,data in pairs(energyTable[curSet].types) do
  _G["changeType"..Type]=function()changeType(Type)end
  local pos={}
  if count<=3 then
   pos={2-(1*count),0,-3}
  else
   pos={1.7+(-3.4*(count%2)),0,-1.8+(1.2*math.floor((count-4)/2))}
  end
  butWrapper(params,{pos[1]*-1,pos[2],pos[3]},"",Type,"changeType"..Type)
  XMLTable[#XMLTable+1]={
   tag="Image",
   attributes={
    image=Type,
    height=112.5,
    width=90,
    position=tostring(pos[1]*100).." "..tostring(pos[3]*100).." -10",
    rotation="0 0 180",
    raycastTarget=false
  }}
  count=count+1
 end
 self.UI.setXmlTable(XMLTable)
end

function butWrapper(params,pos,label,tool,func)
 params.position=pos
 params.label=label
 params.tooltip=tool
 params.click_function=func
 self.createButton(params)
end

function changeType(newType)
 curType=newType
 changeArt()
end

function prevSet()
 curSet=curSet-1
 if curSet==0 then curSet=#energyTable end
 changeArt()
end

function nextSet()
 curSet=curSet+1
 if curSet>#energyTable then curSet=1 end
 changeArt()
end

function onObjectLeaveContainer(cont,leaving)
 if cont~=self then return end
 local setTable=energyTable[curSet]
 if setTable.basic then
  leaving.setName("Basic "..curType.." Energy")
 else
  leaving.setName(curType.." Energy")
 end
 leaving.setDescription((setTable.types[curType].setName or setTable.set).." #"..setTable.types[curType].num)
 if setTable.rarity then leaving.setDescription(leaving.getDescription().." "..setTable.rarity)end
 leaving.memo=((setTable.types[curType].date or setTable.date)..buildCardNumber(setTable.types[curType].num))
end

function removeLeadingZeros(num)
 if tonumber(num)then return string.format("%u", num)else return num end
end

function getImageURL()
 local setTable=energyTable[curSet]
 if setTable.api and not setTable.types[curType].noApi then
  local settings=Global.GetTable("PPacks")or{qual=false}
  local size="large"
  if settings.qual==false then size="medium"end
  return"https://images.scrydex.com/pokemon/"..(setTable.code or setTable.types[curType].code).."%2D"..removeLeadingZeros(setTable.types[curType].num).."/"..size
 elseif setTable.types[curType].steamUrl then
  return getSteamUrl(setTable.types[curType].steamUrl)
 else
  return setTable.types[curType].image
 end
end

function getDeckID()
 local setTable=energyTable[curSet]
 if setTable.DeckID and not setTable.types[curType].DeckID then
  return setTable.DeckID+(tonumber(setTable.types[curType].num)or 0)
 else
  return setTable.types[curType].DeckID
 end
end

function getSteamUrl(url)
 if url then return"https://steamusercontent-a.akamaihd.net/ugc/"..url.."/"end
end

function buildCardNumber(cardNum)
 local numOnly=string.gsub(cardNum,"[^%d]","")
 if numOnly~=cardNum then
  local finalNum=(tonumber(numOnly)or 0)+500
  for c in cardNum:gmatch"[^%d]" do
   if c=="?"then c="}"end
   if c=="!"then c="{"end
   finalNum=string.byte(c)-65+finalNum
  end
  cardNum=tostring(finalNum)
 end
 while #cardNum<3 do cardNum="0"..cardNum end
 return cardNum
end

function getCustomData()
 return{FaceURL=getImageURL(),
  BackURL="https://steamusercontent-a.akamaihd.net/ugc/809997459557414686/9ABD9158841F1167D295FD1295D7A597E03A7487/",
  NumWidth=1,
  NumHeight=1,
  BackIsHidden=true,
 }
end

function changeArt()
 setTable=energyTable[curSet]
 if not setTable.types[curType] then
  curType="Grass"
 end
 saveData()
 self.setDescription(setTable.set.." "..curType.." Energy")
 self.setCustomObject({diffuse=getImageURL()})
 selfData=self.getData()
 selfData.ContainedObjects[1].CardID=getDeckID()*100
 selfData.ContainedObjects[1].CustomDeck={
   [getDeckID()]=getCustomData()
 }
 self.destruct()
 spawnObjectData({data=selfData})
end

function saveData()
  local save={curType=curType,curSet=curSet}
  self.script_state=json.serialize(save)
end
